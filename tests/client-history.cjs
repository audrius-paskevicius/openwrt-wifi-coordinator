'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.join(__dirname,'..');
const graph=new Function('baseclass','chartlib',fs.readFileSync(path.join(root,'channel-coordinator/files/wifi-coordinator.graphs.js'),'utf8'))({extend:x=>x},{Chart:function(canvas,config){return config;}});
const rows=[{radio:'radio0',source:'one',start:0,end:10,count:0},{radio:'radio0',source:'one',start:10,end:20,count:2},{radio:'radio0',source:'one',start:30,end:35,count:2},{radio:'radio0',source:'two',start:35,end:40,count:1}];
const set=graph.clientData(rows,['radio0'],5,38)[0];
assert.deepEqual(set.data.map(p=>[p.x,p.y]),[[5,0],[10,0],[10,2],[20,2],[30,null],[30,2],[35,2],[35,null],[35,1],[38,1]]);
assert.equal(set.borderColor,graph.colour('radio0',0));
assert.equal(set.borderWidth,graph.trafficData([],['radio0'])[0].borderWidth);
assert.equal(set.spanGaps,false);
assert.equal(graph.clientData([],['radio0'],0,100)[0].data.length,0);
assert.equal(graph.clientData([{...rows[0],count:null}],['radio0'],0,100)[0].data.length,0);
const chart=graph.clientChart(null,rows,['radio0'],0,50);
assert.equal(chart.options.scales.y.ticks.precision,0);
assert.equal(chart.options.scales.y.min,0);
const source=fs.readFileSync(path.join(root,'channel-coordinator/files/wifi-history.js'),'utf8');
assert(source.indexOf("heading(_('Where each radio spent its time')")<source.indexOf("heading(_('Clients on each radio over time')"));
assert(source.indexOf("heading(_('Clients on each radio over time')")<source.indexOf("heading(_('Observed traffic over time')"));
assert(source.includes("'data-tooltip':detail")&&source.includes("'tabindex':'0'"));
console.log('PASS: client-count steps, zeroes, gaps, reboot boundaries, shared styling and graph title help');
